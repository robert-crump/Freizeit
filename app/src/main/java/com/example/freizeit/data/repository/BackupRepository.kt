package com.example.freizeit.data.repository

import android.content.Context
import android.net.Uri
import androidx.room.withTransaction
import com.example.freizeit.data.BackupData
import com.example.freizeit.data.BackupJsonCodec
import com.example.freizeit.data.BackupParseException
import com.example.freizeit.data.FreizeitDatabase
import java.io.InputStreamReader
import java.io.OutputStreamWriter
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext

/**
 * Exports/imports all user data (#74): verdicts (favorites among them), the user's edits to
 * places (`poi_override`, #73), custom places (issue #45), the check-in history and the
 * settings. OSM `poi` rows are excluded; they're regenerated by the extraction pipeline import
 * (see [PoiRepository]) — `custom_poi` has no such other source of truth, so unlike `poi` it IS
 * included here. Geofence state is excluded too: it follows from the restored verdicts and
 * notification switches, and the app re-syncs geofences as soon as those change.
 */
class BackupRepository(
    private val context: Context,
    private val db: FreizeitDatabase,
    private val settingsRepository: SettingsRepository
) {

    /** @return number of verdicts + overrides + custom POIs + visits written */
    suspend fun exportTo(uri: Uri): Int = withContext(Dispatchers.IO) {
        val verdicts = db.verdictDao().getAll()
        val overrides = db.poiOverrideDao().getAll()
        val customPois = db.customPoiDao().getAll()
        val visits = db.visitDao().getAll()
        val settings = settingsRepository.snapshot()
        val output = context.contentResolver.openOutputStream(uri)
            ?: throw BackupParseException("Could not open the destination file")
        output.use { stream ->
            OutputStreamWriter(stream, Charsets.UTF_8).use { writer ->
                BackupJsonCodec.write(
                    writer,
                    BackupData(
                        exportedAt = System.currentTimeMillis(),
                        verdicts = verdicts,
                        overrides = overrides,
                        customPois = customPois,
                        visits = visits,
                        settings = settings
                    )
                )
            }
        }
        verdicts.size + overrides.size + customPois.size + visits.size
    }

    /**
     * Parses the file at [uri] entirely before writing, then replaces the verdict, override,
     * custom-POI and visit tables in one transaction and the settings right after — a restore
     * is a wholesale replace, not a merge, matching the fresh-install use case.
     *
     * @return number of verdicts + overrides + custom POIs + visits restored
     * @throws BackupParseException on unreadable or malformed files
     */
    suspend fun importFrom(uri: Uri): Int = withContext(Dispatchers.IO) {
        val input = context.contentResolver.openInputStream(uri)
            ?: throw BackupParseException("Could not open the selected file")
        val data = input.use { stream ->
            BackupJsonCodec.read(InputStreamReader(stream, Charsets.UTF_8))
        }
        db.withTransaction {
            db.verdictDao().deleteAll()
            db.verdictDao().upsertAll(data.verdicts)
            db.poiOverrideDao().deleteAll()
            db.poiOverrideDao().upsertAll(data.overrides)
            db.customPoiDao().deleteAll()
            db.customPoiDao().upsertAll(data.customPois)
            db.visitDao().deleteAll()
            db.visitDao().insertAll(data.visits)
        }
        settingsRepository.restore(data.settings)
        data.verdicts.size + data.overrides.size + data.customPois.size + data.visits.size
    }
}
